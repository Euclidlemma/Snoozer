package com.example.snoozer.ui.theme

import androidx.compose.ui.unit.dp

/**
 * The only spacing steps screens should use, so gaps line up across the app.
 * XS: inside a component (icon to label). S: between related items. M: card padding and
 * screen gutters. L: between sections.
 */
object Spacing {
    val XS = 4.dp
    val S = 8.dp
    val M = 16.dp
    val L = 24.dp
}
